import React, { useState } from 'react';
import {
  CheckCircle2,
  ChevronRight,
  Clock,
  ArrowRight,
  ShieldCheck,
  AlertCircle,
  FileCheck,
  Sparkles,
  Lock,
  Unlock
} from 'lucide-react';
import { Button } from '../../../components/ui/Button';
import { Modal } from '../../../components/ui/Modal';
import { useToast } from '../../../components/ui/Toast';
import { useMatters } from '../../../context/MatterContext';
import { useTasks } from '../../../context/TaskContext';

export const STANDARD_MATTER_STAGES = [
  { id: 'stage-1', name: 'Intake & Conflicts', code: 'INT', requiredFields: ['Conflict Check Cleared', 'Engagement Letter Signed', 'IOLTA Retainer Deposited'] },
  { id: 'stage-2', name: 'Pleadings & Service', code: 'PLD', requiredFields: ['Complaint Filed with Court', 'Summons Served on Registered Agent', 'Answer or Default Logged'] },
  { id: 'stage-3', name: 'Fact Discovery', code: 'DISC', requiredFields: ['Utah R. Civ. P. 26 Initial Disclosures Exchanged', 'Written Interrogatories Served', 'Key Fact Witness Depositions Completed'] },
  { id: 'stage-4', name: 'Expert Discovery', code: 'EXP', requiredFields: ['Expert Witness Retainers Executed', 'Rule 26(a)(2) Expert Reports Exchanged', 'Expert Rebuttal Depositions Conducted'] },
  { id: 'stage-5', name: 'Dispositive Motions & Pre-Trial', code: 'MOT', requiredFields: ['Rule 56 Summary Judgment Briefing Concluded', 'Pre-Trial Hearing Completed', 'Jury Instructions Filed'] },
  { id: 'stage-6', name: 'Trial & Resolution', code: 'TRL', requiredFields: ['Trial Exhibits Exchanged', 'Final Verdict / Settlement Agreement Executed', 'Closing Accounting Approved'] },
];

export function StageProgressBar({ matter }) {
  const { updateMatter } = useMatters();
  const { addTask } = useTasks();
  const { addToast } = useToast();

  const currentStageIndex = STANDARD_MATTER_STAGES.findIndex(s => s.name.toLowerCase() === (matter.stage || 'Fact Discovery').toLowerCase()) !== -1
    ? STANDARD_MATTER_STAGES.findIndex(s => s.name.toLowerCase() === (matter.stage || 'Fact Discovery').toLowerCase())
    : 2; // Default to Fact Discovery if unset

  const currentStage = STANDARD_MATTER_STAGES[currentStageIndex];
  const nextStage = currentStageIndex < STANDARD_MATTER_STAGES.length - 1 ? STANDARD_MATTER_STAGES[currentStageIndex + 1] : null;

  const [isAdvanceModalOpen, setIsAdvanceModalOpen] = useState(false);
  const [completedRequirements, setCompletedRequirements] = useState(() => {
    // Default the first 2 requirements as checked for demonstration realism
    const initial = {};
    if (currentStage?.requiredFields) {
      currentStage.requiredFields.forEach((req, idx) => {
        initial[req] = idx === 0 || idx === 1;
      });
    }
    return initial;
  });

  const allRequirementsMet = currentStage?.requiredFields.every(req => completedRequirements[req]);

  const handleToggleRequirement = (req) => {
    setCompletedRequirements(prev => ({ ...prev, [req]: !prev[req] }));
  };

  const handleAdvanceStage = () => {
    if (!nextStage) return;

    // 1. Update Matter Stage in Context
    updateMatter(matter.id, {
      stage: nextStage.name,
      status: nextStage.name === 'Trial & Resolution' ? 'In Trial' : 'Active',
      lastStageAdvanceDate: new Date().toISOString().split('T')[0],
    });

    // 2. Automatically spawn next-stage workflow tasks (Filevine Simulation)
    let spawnedCount = 0;
    if (nextStage.name === 'Expert Discovery') {
      addTask({
        title: 'Retain Economics Damages Expert & Issue Deposition Subpoena',
        matterId: matter.id,
        matterTitle: matter.title,
        clientId: matter.clientId,
        clientName: matter.clientName,
        assignedToId: 'usr-2',
        assignedToName: 'Thomas Bludworth, Esq.',
        dueDate: '2026-12-01',
        priority: 'High',
        status: 'Not Started',
        description: 'Auto-generated by Workflow Engine upon advancing to Expert Discovery stage.',
      });
      addTask({
        title: 'Compile Expert Report Production Index & Rule 26 Exhibits',
        matterId: matter.id,
        matterTitle: matter.title,
        clientId: matter.clientId,
        clientName: matter.clientName,
        assignedToId: 'usr-4',
        assignedToName: 'Marcus Vance',
        dueDate: '2026-12-05',
        priority: 'Medium',
        status: 'Not Started',
        description: 'Auto-generated litigation task for expert witness index disclosures.',
      });
      spawnedCount = 2;
    } else if (nextStage.name === 'Dispositive Motions & Pre-Trial') {
      addTask({
        title: 'Draft Rule 56 Motion for Summary Judgment Statement of Undisputed Material Facts',
        matterId: matter.id,
        matterTitle: matter.title,
        clientId: matter.clientId,
        clientName: matter.clientName,
        assignedToId: 'usr-2',
        assignedToName: 'Thomas Bludworth, Esq.',
        dueDate: '2026-12-15',
        priority: 'Urgent',
        status: 'Not Started',
        description: 'Auto-generated by Workflow Engine upon advancing to Dispositive Motions stage.',
      });
      spawnedCount = 1;
    } else {
      addTask({
        title: `Next Stage Kickoff Review: ${nextStage.name}`,
        matterId: matter.id,
        matterTitle: matter.title,
        clientId: matter.clientId,
        clientName: matter.clientName,
        assignedToId: 'usr-4',
        assignedToName: 'Marcus Vance',
        dueDate: '2026-11-25',
        priority: 'High',
        status: 'Not Started',
        description: `Auto-generated initial checklist for ${nextStage.name}.`,
      });
      spawnedCount = 1;
    }

    setIsAdvanceModalOpen(false);
    addToast(
      `Matter advanced to "${nextStage.name}". Workflow Engine auto-spawned ${spawnedCount} new litigation tasks!`,
      'success'
    );
  };

  return (
    <div className="bg-white p-4 rounded border border-[#D9D6CF] shadow-xs space-y-3">
      {/* Header Info */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 pb-2 border-b border-[#F5F0E5]">
        <div className="flex items-center gap-2">
          <span className="text-[10px] uppercase font-bold tracking-wider text-[#A4432B]">
            Matter Workflow Phase:
          </span>
          <span className="text-xs font-serif font-bold text-[#06244B]">
            {currentStage.name}
          </span>
          <span className="text-[10px] bg-[#F5F0E5] text-[#06244B] px-2 py-0.5 rounded font-semibold border border-[#D9D6CF]">
            Stage {currentStageIndex + 1} of {STANDARD_MATTER_STAGES.length}
          </span>
        </div>

        {nextStage && (
          <Button
            size="xs"
            variant="primary"
            onClick={() => setIsAdvanceModalOpen(true)}
            className="self-start sm:self-auto cursor-pointer"
          >
            <span>Advance to {nextStage.name}</span>
            <ChevronRight className="w-3.5 h-3.5 ml-1" />
          </Button>
        )}
      </div>

      {/* Horizontal Chevron Pipeline Stepper */}
      <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-6 gap-1.5 pt-1">
        {STANDARD_MATTER_STAGES.map((stage, idx) => {
          const isCompleted = idx < currentStageIndex;
          const isCurrent = idx === currentStageIndex;
          const isUpcoming = idx > currentStageIndex;

          return (
            <div
              key={stage.id}
              className={`p-2 rounded border text-left transition-all ${
                isCompleted
                  ? 'bg-emerald-50/70 border-emerald-300 text-emerald-900'
                  : isCurrent
                  ? 'bg-[#06244B] border-[#06244B] text-white shadow-xs'
                  : 'bg-[#FAF7F0] border-[#D9D6CF] text-[#667085]'
              }`}
            >
              <div className="flex items-center justify-between mb-1">
                <span className={`text-[9px] font-mono font-bold uppercase tracking-wider ${
                  isCurrent ? 'text-[#F5F0E5]' : isCompleted ? 'text-emerald-700' : 'text-[#667085]'
                }`}>
                  Phase 0{idx + 1}
                </span>
                {isCompleted && <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />}
                {isCurrent && <Clock className="w-3.5 h-3.5 text-amber-300 animate-pulse" />}
              </div>

              <span className={`text-[11px] font-semibold block leading-tight truncate ${
                isCurrent ? 'text-white' : isCompleted ? 'text-[#06244B]' : 'text-[#667085]'
              }`}>
                {stage.name}
              </span>
            </div>
          );
        })}
      </div>

      {/* Stage Advance Modal with Stage-Gate Checklist */}
      {isAdvanceModalOpen && nextStage && (
        <Modal
          isOpen={isAdvanceModalOpen}
          onClose={() => setIsAdvanceModalOpen(false)}
          title={`Advance Matter: "${currentStage.name}" → "${nextStage.name}"`}
          size="md"
        >
          <div className="space-y-4 text-xs text-[#202A35]">
            <div className="p-3 bg-[#F5F0E5]/60 rounded border border-[#D9D6CF] flex items-start gap-2.5">
              <ShieldCheck className="w-4 h-4 text-[#06244B] mt-0.5 flex-shrink-0" />
              <div>
                <p className="font-semibold text-[#06244B]">Stage-Gate Compliance Validation:</p>
                <p className="text-[11px] text-[#667085] leading-relaxed mt-0.5">
                  Under Utah law practice standards, proceeding to <strong>{nextStage.name}</strong> requires all predecessor conditions for <strong>{currentStage.name}</strong> to be satisfied.
                </p>
              </div>
            </div>

            {/* Required Checklist Items */}
            <div className="space-y-2">
              <span className="text-[11px] font-bold text-[#06244B] uppercase tracking-wider block">
                Required Pre-requisites Checklist:
              </span>

              {currentStage.requiredFields.map((req) => (
                <label
                  key={req}
                  className="flex items-start gap-2.5 p-2.5 rounded border border-[#D9D6CF] bg-white hover:bg-[#FAF7F0] cursor-pointer transition-colors"
                >
                  <input
                    type="checkbox"
                    checked={!!completedRequirements[req]}
                    onChange={() => handleToggleRequirement(req)}
                    className="w-4 h-4 mt-0.5 rounded text-[#A4432B] focus:ring-[#A4432B] border-[#D9D6CF]"
                  />
                  <div className="flex-1">
                    <span className={`font-semibold block ${completedRequirements[req] ? 'line-through text-[#667085]' : 'text-[#06244B]'}`}>
                      {req}
                    </span>
                    <span className="text-[10px] text-[#667085]">Verified by responsible attorney or senior paralegal</span>
                  </div>
                </label>
              ))}
            </div>

            {/* Automated Actions Preview */}
            <div className="p-3 bg-blue-50/60 rounded border border-blue-200 text-blue-900 space-y-1 text-[11px]">
              <span className="font-bold flex items-center gap-1">
                <Sparkles className="w-3.5 h-3.5 text-blue-600" />
                <span>Automated Workflow Engine Actions Triggered upon Advancement:</span>
              </span>
              <ul className="list-disc pl-4 space-y-0.5 text-[10px] text-blue-800">
                <li>Update master matter stage index to <strong>"{nextStage.name}"</strong></li>
                <li>Spawn statutory discovery &amp; expert disclosure tasks for assigned staff</li>
                <li>Record timestamped transition in firm audit logs</li>
              </ul>
            </div>

            <div className="flex items-center justify-between pt-2 border-t border-[#D9D6CF]">
              <Button type="button" variant="outline" size="sm" onClick={() => setIsAdvanceModalOpen(false)}>
                Cancel
              </Button>
              <Button
                type="button"
                variant="primary"
                size="sm"
                disabled={!allRequirementsMet}
                onClick={handleAdvanceStage}
                className={allRequirementsMet ? '' : 'opacity-50 cursor-not-allowed'}
              >
                <span>Confirm &amp; Advance Stage</span>
                <ArrowRight className="w-3.5 h-3.5 ml-1.5" />
              </Button>
            </div>
          </div>
        </Modal>
      )}
    </div>
  );
}

